#!/usr/bin/env python3
"""Turn a program built with the GNU H8 tools into a CyOS application.

    cybiko_mkapp.py --at0 A.coff --at1 B.coff --entry SYM --name NAME
                    [--icon ICON.txt] [--help HELP.txt] [--type root]
                    [--header OUT.h --symbol NAME] OUT.app

A.coff and B.coff are the same program linked at 0 and at 0x10000 (see
src/cybiko_apps/link.ld). The words that differ by 0x10000 are the ones the
CyOS loader has to relocate. The result is a CyOS module (main.e) in an
application archive with its description (root.inf), a desktop icon and a
help page. With --header it is also written as a C array.

The module format (CyOS 1.5, found in the Xtreme's own applications):

    0   u16  91af            magic
    2   u16  2               (always 2)
    4   u32  image size      code and data, loaded from offset 2c
    8   u32  bss size        zeroed bytes after the image
    c   u32  0
   10   u32  names size      library names after the image, NUL-terminated;
                             the first is "ordinals" (the kernel)
   14   u32  fixups size     4-byte records after the names
   18   u32  entry           offset of main(int argc, char **argv, bool start)
   1c  4u32  (C++ static constructor and destructor tables, unused here)

A fixup record is a type byte and a 24-bit offset into the image. Type 3
adds the load address to the 32-bit word there, type 2 to the 24-bit address
of a jsr/jmp; 0x80+n puts the address of export number (the word's low 24
bits) of library n there. This tool writes types 2 and 3 only: programs for
the emulator call it through CY_APP_OP instead of importing CyOS functions.
Python 3 and the GNU H8 binutils (binutils-h8300-hms).
"""
import argparse
import os
import struct
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cyarchive  # noqa: E402

TOOL = "h8300-hitachi-coff-"
SHIFT = 0x10000


def image(coff):
    """The loaded bytes (.text, which holds code and data) and the symbols."""
    binary = coff + ".bin"
    subprocess.run([TOOL + "objcopy", "-O", "binary", "-j", ".text", coff, binary], check=True)
    data = open(binary, "rb").read()
    os.unlink(binary)
    syms = {}
    out = subprocess.run([TOOL + "nm", coff], check=True, capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3:
            syms[parts[2]] = int(parts[0], 16)
    return data, syms


def fixups(a, b):
    """Offsets of the words that moved with the base, and their types."""
    if len(a) != len(b):
        sys.exit("the two links differ in size")
    out = []
    moved = bytearray(a)
    i = 0
    while i + 4 <= len(a):
        wa, wb = struct.unpack_from(">I", a, i)[0], struct.unpack_from(">I", b, i)[0]
        if (wb - wa) & 0xffffffff == SHIFT:
            out.append((2 if wa >> 24 in (0x5a, 0x5e) else 3, i))
            struct.pack_into(">I", moved, i, wb)
            i += 4
        else:
            i += 2
    if bytes(moved) != b:
        bad = next(k for k in range(len(a)) if moved[k] != b[k])
        sys.exit("offset %x: a change the loader cannot make" % bad)
    return out


def module(at0, at1, entry):
    a, syms = image(at0)
    b, syms1 = image(at1)
    if entry not in syms:
        sys.exit("no symbol %s" % entry)
    bss = syms["__bss_end"] - syms["__bss_start"]
    if syms1["__bss_end"] - syms1["__bss_start"] != bss or len(a) != syms["__image_end"]:
        sys.exit("unexpected layout; link with src/cybiko_apps/link.ld")
    names = b"ordinals\0"
    recs = b"".join(struct.pack(">I", t << 24 | off) for t, off in fixups(a, b))
    head = struct.pack(">HHIIIIII16x", 0x91AF, 2, len(a), bss, 0, len(names), len(recs), syms[entry])
    return head + a + names + recs


def icon(path):
    """A picture drawn as text: one row a line, '.' white, '-' light grey,
    '+' dark grey, '#' black."""
    rows = [r.rstrip("\n") for r in open(path) if r.strip()]
    w, h = max(len(r) for r in rows), len(rows)
    stride = (w + 3) // 4
    pix = bytearray(stride * h)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            v = ".-+#".index(ch)
            pix[y * stride + x // 4] |= v << (6 - 2 * (x % 4))
    return bytes([2, 1, w, h, 0, 0, w, h]) + bytes(pix)


def c_array(blob, symbol):
    lines = ["/* Generated by tools/cybiko_mkapp.py from src/cybiko_apps; do not edit. */",
             "#pragma once", "#include <stdint.h>",
             "static const uint8_t %s[%d] = {" % (symbol, len(blob))]
    for i in range(0, len(blob), 16):
        lines.append("    " + "".join("0x%02x," % c for c in blob[i:i + 16]))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description="Make a CyOS .app from an H8S program")
    p.add_argument("--at0", required=True)
    p.add_argument("--at1", required=True)
    p.add_argument("--entry", default="_main")
    p.add_argument("--name", required=True)
    p.add_argument("--type", default="root", help="root (desktop), app or game")
    p.add_argument("--version", default="1.0.0")
    p.add_argument("--icon")
    p.add_argument("--help-file", dest="help_file")
    p.add_argument("--header")
    p.add_argument("--symbol")
    p.add_argument("out")
    a = p.parse_args()
    main_e = module(a.at0, a.at1, a.entry)
    inf = [a.type, a.name, "", "", "", "", a.name.replace(" ", "_"), a.version, "1.5.1"]
    parts = [("root.inf", ("\r\n".join(inf) + "\r\n").encode("latin-1"), True)]
    if a.icon:
        parts.append(("0.ico", icon(a.icon), True))
    if a.help_file:
        text = open(a.help_file).read().replace("\r\n", "\n").replace("\n", "\r\n")
        parts.append(("0.help", text.encode("latin-1"), True))
    parts.append(("main.e", main_e, True))
    blob = cyarchive.cy_archive(parts)
    with open(a.out, "wb") as f:
        f.write(blob)
    if a.header:
        with open(a.header, "w") as f:
            f.write(c_array(blob, a.symbol or "cy_app"))
    print("%s: %d bytes (main.e %d)" % (a.out, len(blob), len(main_e)))


if __name__ == "__main__":
    main()
